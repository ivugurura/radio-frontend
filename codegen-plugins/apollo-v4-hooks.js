/*
  Custom GraphQL Codegen plugin to generate Apollo Client v4-compatible React hooks
  for each operation (Query/Mutation/Subscription) using the client-preset artifacts.

  It produces `src/graphql/generated/hooks.ts` with wrappers like:
    export function useLoginUserMutation(options?: MutationHookOptions<...>) { return useMutation(...); }
*/

/** @typedef {import('@graphql-codegen/plugin-helpers').PluginFunction} PluginFunction */

const { Kind } = require('graphql');

/** @type {PluginFunction} */
module.exports.plugin = (schema, documents) => {
  /** @type {Array<{name:string, type:'query'|'mutation'|'subscription'}>} */
  const ops = [];

  for (const doc of documents) {
    const ast = doc.document;
    if (!ast) continue;
    for (const def of ast.definitions || []) {
      if (
        def.kind === Kind.OPERATION_DEFINITION &&
        def.name &&
        def.name.value
      ) {
        const opName = def.name.value;
        const opType = def.operation; // 'query' | 'mutation' | 'subscription'
        ops.push({ name: opName, type: opType });
      }
    }
  }

  if (ops.length === 0) {
    return `// No operations found for hooks generation\n`;
  }

  // Build imports
  const uniqueOps = Array.from(
    new Map(ops.map((o) => [o.name + ':' + o.type, o])).values()
  );

  const docImports = uniqueOps.map((o) => `${o.name}Document`).join(', ');
  const typeImports = uniqueOps
    .map(
      (o) =>
        `${o.name}${capitalize(opTypeSuffix(o.type))}, ${o.name}${capitalize(opTypeSuffix(o.type))}Variables`
    )
    .join(', ');

  const header = `/* eslint-disable */\n// Generated by custom apollo-v4-hooks plugin. Do not edit manually.\n`;
  // Determine which hooks are needed
  const needMutation = uniqueOps.some((o) => o.type === 'mutation');
  const needQuery = uniqueOps.some((o) => o.type === 'query');
  const needLazyQuery = needQuery; // generate lazy variant when a query exists
  const needSubscription = uniqueOps.some((o) => o.type === 'subscription');
  const hookImports = [
    needQuery ? 'useQuery' : null,
    needLazyQuery ? 'useLazyQuery' : null,
    needMutation ? 'useMutation' : null,
    needSubscription ? 'useSubscription' : null,
  ]
    .filter(Boolean)
    .join(', ');

  // Apollo v4 exports React hooks from the package root in ESM builds.
  const imports = `${hookImports ? `import { ${hookImports} } from '@apollo/client/react';\n` : ''}import { ${docImports} } from './graphql';\nimport type { ${typeImports} } from './graphql';\n`;

  const blocks = uniqueOps.map((o) => {
    const typeBase = `${o.name}${capitalize(opTypeSuffix(o.type))}`;
    const typeVars = `${o.name}${capitalize(opTypeSuffix(o.type))}Variables`;
    const docConst = `${o.name}Document`;
    if (o.type === 'mutation') {
      return `export function use${o.name}Mutation(options?: Parameters<typeof useMutation<${typeBase}, ${typeVars}>>[1]) {\n  return useMutation<${typeBase}, ${typeVars}>(${docConst}, options);\n}\n`;
    }
    if (o.type === 'query') {
      return `export function use${o.name}Query(options?: Parameters<typeof useQuery<${typeBase}, ${typeVars}>>[1]) {\n  return useQuery<${typeBase}, ${typeVars}>(${docConst}, options);\n}\nexport function use${o.name}LazyQuery(options?: Parameters<typeof useLazyQuery<${typeBase}, ${typeVars}>>[1]) {\n  return useLazyQuery<${typeBase}, ${typeVars}>(${docConst}, options);\n}\n`;
    }
    if (o.type === 'subscription') {
      return `export function use${o.name}Subscription(options?: Parameters<typeof useSubscription<${typeBase}, ${typeVars}>>[1]) {\n  return useSubscription<${typeBase}, ${typeVars}>(${docConst}, options);\n}\n`;
    }
    return '';
  });

  return header + imports + blocks.join('\n');
};

function opTypeSuffix(op) {
  if (op === 'query') return 'Query';
  if (op === 'mutation') return 'Mutation';
  if (op === 'subscription') return 'Subscription';
  return '';
}

function capitalize(s) {
  return s.charAt(0).toUpperCase() + s.slice(1);
}
